// Wraps the built page script IIFE (.cache/client) into src/client/generated.ts as a string constant.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = ".cache/client";
const file = readdirSync(dir).find((f) => /^page-script.*\.js$/.test(f));
if (!file) throw new Error(`no built page script in ${dir}; run tsdown --config tsdown.client.config.ts first`);
const code = readFileSync(join(dir, file), "utf8").trim();
const placeholders = code.split("__CFG__").length - 1;
if (placeholders !== 1) throw new Error(`expected exactly one __CFG__ placeholder, found ${placeholders}`);
if (code.includes("__TEST_HOOKS__") || code.includes("__trusted")) throw new Error("test hooks leaked into the production build");

writeFileSync(
	"src/client/generated.ts",
	`// Generated by scripts/embed-client.mjs from src/client/page-script.ts. Do not edit.\nexport const PAGE_SCRIPT: string = ${JSON.stringify(code)};\n`,
);
console.log(`src/client/generated.ts: ${code.length} bytes`);
